//Declare una variable con un valor inicial. Utilice operadores de asignación compuesta (+=,
//-=, *=) para modificar su valor y muestre cada cambio en consola.

let variable = 10;
console.log("Valor inicial: " + variable);

variable += 5;
console.log("Después de += 5: " + variable);

variable -= 3;
console.log("Después de -= 3: " + variable);

variable *= 2;
console.log("Después de *= 2: " + variable);