//Declare dos variables numéricas. Realice todas las operaciones aritméticas básicas
//(suma, resta, multiplicación, división y módulo) y muestre cada resultado por separado en
//consola.

let num1 = 10;
let num2 = 5;

// Suma
let suma = num1 + num2;
console.log("Suma: " + suma);

// Resta
let resta = num1 - num2;
console.log("Resta: " + resta);
// Multiplicación
let multiplicacion = num1 * num2;
console.log("Multiplicación: " + multiplicacion);
// División
let division = num1 / num2;
console.log("División: " + division);
// Módulo   
let modulo = num1 % num2;
console.log("Módulo: " + modulo);

